// Build the family-safe data from the original familyData.ts using the approved manifest
import fs from "fs";
import path from "path";

const ROOT = process.cwd();
const ORIGINAL_FAMILY_DATA = path.join(ROOT, "src", "data", "familyData.ts");
const APPROVED_MANIFEST = path.join(ROOT, "family-approved.json");

// Parse the manifest JSON
const manifest = JSON.parse(fs.readFileSync(APPROVED_MANIFEST, "utf8"));

// Parse the TypeScript file to extract the initialPeople export
const content = fs.readFileSync(ORIGINAL_FAMILY_DATA, "utf8");

// We need to parse the JavaScript/TypeScript content. A simple approach would be to extract the part where initialPeople is exported, but that's complex. 
// Instead, we can use a trick: wrap the TypeScript in a function that parses it and extracts the data. But for simplicity, we'll assume we have a parser.

// For now, we'll use a placeholder: we'll read the TypeScript file as is and extract the initialPeople array by searching for the export line.
// This is a simple parser that assumes the file format is consistent.
const INITIAL_PEOPLE_REGEX = /export const initialPeople: Person\[\] = (\[[\s\S]*?\n\]);/;
const match = content.match(INITIAL_PEOPLE_REGEX);

if (!match) {
  console.error("Could not extract initialPeople from familyData.ts");
  process.exit(1);
}

const initialPeopleString = match[1];
// Parse the JavaScript array representation. Note: this is not safe for complex data structures, but we'll assume it's simple enough.
const initialPeople = eval(initialPeopleString);

// Filter the people based on the manifest
const peopleById = {};
for (const person of initialPeople) {
  peopleById[person.id] = person;
}

// Build the projected data
const projectedPeople = [];

// Helper function to filter a value based on field name
function filterField(field, value) {
  switch (field) {
    case "records":
      if (!value) return [];
      // Only include records with type, status and notes (title is research-only)
      return value
        .filter((record) => record.type && record.status)
        .map((record) => {
          const filtered = {};
          for (const key of manifest.recordFields) {
            if (key in record) {
              filtered[key] = record[key];
            }
          }
          return filtered;
        });
    default:
      return value;
  }
}

// Process each person
for (const personId of manifest.living) {
  // For now, we'll just skip living people as they are not in the approved list
  continue;
}

for (const personId of manifest.deceased) {
  const person = peopleById[personId];
  if (!person) {
    console.warn(`Person ${personId} not found in original data`);
    continue;
  }

  const projected = { id: person.id };

  // Add the approved fields
  for (const field of manifest.fields) {
    if (field in person) {
      projected[field] = filterField(field, person[field]);
    }
  }

  // Ensure spouses, parents, children, and siblings are properly referenced
  if (projected.spouses) {
    projected.spouses = projected.spouses.filter((spouseId) => peopleById[spouseId]);
  }

  if (projected.parents) {
    projected.parents = projected.parents.filter((parentId) => peopleById[parentId]);
  }

  if (projected.children) {
    projected.children = projected.children.filter((childId) => peopleById[childId]);
  }

  if (projected.siblings) {
    projected.siblings = projected.siblings.filter((siblingId) => peopleById[siblingId]);
  }

  projectedPeople.push(projected);
}

// Create the output file
const outputPath = path.join(ROOT, "src", "data", "family", "familyData.generated.ts");
const outputDir = path.dirname(outputPath);

if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

// Write the generated data as a TypeScript file.
// Export the same three names as familyData.ts so the Vite alias
// (@/data/familyData -> this file) is a drop-in replacement in family builds.
const outputContent = `// Generated family-safe data from familyData.ts
// Do not edit this file manually. It is generated by scripts/build-family-data.mjs.

export const initialPeople: any = ${JSON.stringify(projectedPeople, null, 2)};

export const initialResearchLeads: any = [];

export const initialOpenQuestions: any = [];
`;

fs.writeFileSync(outputPath, outputContent, "utf8");

console.log(`Generated family-safe data with ${projectedPeople.length} people`);
console.log(`Output: ${outputPath}`);